# Use the directory where the script is run from (your data folder)
# If CSVs are in a different folder, set DATA_DIR manually e.g.:
# DATA_DIR = "/home/shubham/Documents/geothon_2"
DATA_DIR = os.getcwd()

def file_mtime(path):
    try:
        return os.path.getmtime(path)
    except FileNotFoundError:
        return 0

@st.cache_data(ttl=300)   # re-check every 5 minutes
def load_data():
    files = {
        "risk":     os.path.join(DATA_DIR, "final_risk_scores.csv"),
        "anomaly":  os.path.join(DATA_DIR, "lake_risk_output.csv"),
        "exposure": os.path.join(DATA_DIR, "agricultural_exposure.csv"),
        "lakes":    os.path.join(DATA_DIR, "filtered_glacial_lakes.geojson"),
        "corridors":os.path.join(DATA_DIR, "flood_corridors.geojson"),
        "riskmap":  os.path.join(DATA_DIR, "final_risk_map.geojson"),
    }

    data = {}

    # Required files
    for key in ["risk", "anomaly", "exposure"]:
        path = files[key]
        if os.path.exists(path):
            data[key] = pd.read_csv(path)
        else:
            data[key] = None

    # Optional spatial files
    for key in ["lakes", "corridors", "riskmap"]:
        path = files[key]
        if os.path.exists(path):
            try:
                data[key] = gpd.read_file(path)
            except Exception:
                data[key] = None
        else:
            data[key] = None

    # Last updated = most recent file modification
    data["last_updated"] = max(file_mtime(p) for p in files.values())

    return data

