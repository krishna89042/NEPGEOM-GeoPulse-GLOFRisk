TIER_COLORS = {
    "CRITICAL": "#e74c3c",
    "High":     "#e67e22",
    "Moderate": "#f1c40f",
    "Low":      "#2ecc71"
}

def tier_badge(tier):
    color = TIER_COLORS.get(tier, "#bdc3c7")
    return f'<span style="color:{color};font-weight:bold">{tier}</span>'

def format_last_updated(ts):
    if ts == 0:
        return "Never"
    return datetime.fromtimestamp(ts).strftime("%Y-%m-%d %H:%M")

