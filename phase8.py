    # Plot all monitored lakes
    if data["lakes"] is not None:
        lakes_gdf = data["lakes"]
        risk_lookup = dict(zip(
            data["risk"]["GL_ID"],
            zip(data["risk"]["final_risk"],
                data["risk"]["risk_tier"])
        ))

        for _, row in lakes_gdf.iterrows():
            gl_id   = row["GL_ID"]
            info    = risk_lookup.get(gl_id, (0, "Low"))
            score   = info[0]
            tier    = info[1]
            color   = TIER_COLORS.get(tier, "#2ecc71")
            centroid = row.geometry.centroid

            folium.CircleMarker(
                location = [centroid.y, centroid.x],
                radius   = max(4, score * 12),
                color    = color,
                fill     = True,
                fill_color   = color,
                fill_opacity = 0.75,
                popup = folium.Popup(
                    f"<b>{gl_id}</b><br>"
                    f"Risk: <b>{tier}</b><br>"
                    f"Score: {score:.3f}<br>"
                    f"Basin: {row.get('Basin','')}",
                    max_width=200
                ),
                tooltip = f"{gl_id[-10:]} | {tier}"
            ).add_to(m)

    # Draw flood corridors for top-5
